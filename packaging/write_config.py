"""Bake the Supabase URL and publishable key into hajime/_bundled_config.py at build time.

Both values come from the environment (build.bat reads them from build.env). The publishable
key is designed to ship inside client apps, protected by row-level security; the service-role
or secret key must never be used here, and this script refuses it.
"""

import os
import sys
from pathlib import Path
from urllib.parse import urlparse

TARGET = Path(__file__).resolve().parent.parent / "hajime" / "_bundled_config.py"


def main() -> int:
    url = os.environ.get("HAJIME_SUPABASE_URL", "").strip()
    key = os.environ.get("HAJIME_SUPABASE_ANON_KEY", "").strip()
    parsed = urlparse(url)
    if parsed.scheme != "https" or not parsed.netloc or not key:
        print("ERROR: set HAJIME_SUPABASE_URL (https://...) and HAJIME_SUPABASE_ANON_KEY.")
        return 1
    if key.startswith("sb_secret_") or "service_role" in key:
        print("ERROR: that is a SECRET key. Use the publishable (anon) key instead.")
        return 1
    TARGET.write_text(
        f'"""Generated by build.bat; not committed."""\n\nURL = {f"https://{parsed.netloc}"!r}\n'
        f"ANON_KEY = {key!r}\n", encoding="utf-8")
    print(f"Bundled configuration for {parsed.netloc}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
